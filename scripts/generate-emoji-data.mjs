import {mkdir, readFile, writeFile} from "node:fs/promises";
import {dirname, resolve} from "node:path";
import process from "node:process";
import {fileURLToPath} from "node:url";

const projectRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const sourcePath = resolve(projectRoot, "node_modules/emojibase-data/en/compact.json");
const packagePath = resolve(projectRoot, "node_modules/emojibase-data/package.json");
const aliasesPath = resolve(projectRoot, "scripts/emoji-rpg-aliases.json");
const outputPath = resolve(projectRoot, "src/data/emoji-data.generated.ts");

const GROUPS = [
	{id: "smileys", label: "Smileys & Emotion", icon: "😀", sourceGroup: 0},
	{id: "people", label: "People & Body", icon: "👋", sourceGroup: 1},
	{id: "nature", label: "Animals & Nature", icon: "🐾", sourceGroup: 3},
	{id: "food", label: "Food & Drink", icon: "🍺", sourceGroup: 4},
	{id: "places", label: "Travel & Places", icon: "🗺️", sourceGroup: 5},
	{id: "activities", label: "Activities", icon: "🎲", sourceGroup: 6},
	{id: "objects", label: "Objects", icon: "🎵", sourceGroup: 7},
	{id: "symbols", label: "Symbols", icon: "💠", sourceGroup: 8},
	{id: "flags", label: "Flags", icon: "🏴", sourceGroup: 9},
];

const parseJson = async path => JSON.parse(await readFile(path, "utf8"));
const normalizeEmoji = value => value.replaceAll("\uFE0F", "");
const normalizeSearch = value => value.toLocaleLowerCase("en").replaceAll(/\s+/gu, " ").trim();

const source = await parseJson(sourcePath);
const sourcePackage = await parseJson(packagePath);
const rpgAliases = await parseJson(aliasesPath);

if (!Array.isArray(source) || !Array.isArray(rpgAliases) || typeof sourcePackage.version !== "string") {
	throw new Error("Emojibase input has an unexpected structure.");
}

const byEmoji = new Map();
for (const record of source) {
	if (typeof record.unicode !== "string" || typeof record.label !== "string") continue;
	byEmoji.set(normalizeEmoji(record.unicode), record);
}

const toTuple = (record, extraKeywords = "") => {
	const tags = Array.isArray(record.tags) ? record.tags.filter(tag => typeof tag === "string") : [];
	const labelTerms = new Set(normalizeSearch(record.label).split(" "));
	const searchTerms = [...tags, ...extraKeywords.split(/\s+/u)]
		.map(normalizeSearch)
		.filter(Boolean)
		.filter((term, index, terms) => !labelTerms.has(term) && terms.indexOf(term) === index)
		.join(" ");
	return [record.unicode, record.label, searchTerms];
};

const rpgOptions = rpgAliases.map(alias => {
	const record = byEmoji.get(normalizeEmoji(alias.emoji));
	if (!record) throw new Error(`RPG emoji ${alias.emoji} is missing from Emojibase ${sourcePackage.version}.`);
	return toTuple(record, typeof alias.keywords === "string" ? alias.keywords : "");
});

const standardCategories = GROUPS.map(group => ({
	id: group.id,
	label: group.label,
	icon: group.icon,
	options: source
		.filter(record => record.group === group.sourceGroup && typeof record.unicode === "string" && typeof record.label === "string")
		.sort((left, right) => (left.order ?? Number.MAX_SAFE_INTEGER) - (right.order ?? Number.MAX_SAFE_INTEGER))
		.map(record => toTuple(record)),
}));

const total = standardCategories.reduce((count, category) => count + category.options.length, 0);
if (total < 1900) throw new Error(`Expected at least 1900 standard emojis, received ${total}.`);

const generated = `/* eslint-disable */
// Generated by scripts/generate-emoji-data.mjs from emojibase-data ${sourcePackage.version}.
// Do not edit this file directly. Update the pinned dependency or RPG aliases and regenerate it.

export type GeneratedEmojiTuple = [emoji: string, name: string, searchTerms: string];
export interface GeneratedEmojiCategory {
\tid: string;
\tlabel: string;
\ticon: string;
\toptions: GeneratedEmojiTuple[];
}

export const EMOJI_DATA_SOURCE = "emojibase-data";
export const EMOJI_DATA_VERSION = ${JSON.stringify(sourcePackage.version)};
export const GENERATED_EMOJI_CATEGORIES: GeneratedEmojiCategory[] = ${JSON.stringify([
	{id: "rpg", label: "RPG & Audio", icon: "⚔️", options: rpgOptions},
	...standardCategories,
], null, "\t")};
`;

if (process.argv.includes("--check")) {
	let current = "";
	try { current = await readFile(outputPath, "utf8"); } catch { /* Report the missing output below. */ }
	if (current !== generated) {
		console.error("Generated emoji data is missing or stale. Run npm run generate:emoji.");
		process.exitCode = 1;
	}
} else {
	await mkdir(dirname(outputPath), {recursive: true});
	await writeFile(outputPath, generated, "utf8");
	console.log(`Generated ${total} standard emojis plus ${rpgOptions.length} RPG shortcuts from Emojibase ${sourcePackage.version}.`);
}
